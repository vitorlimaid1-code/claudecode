// Ponte segura entre a interface e o processo principal.
const { contextBridge, ipcRenderer, webUtils } = require('electron');

const inv = (ch, ...a) => ipcRenderer.invoke(ch, ...a);

contextBridge.exposeInMainWorld('api', {
  openProject: filePath => inv('project:open', filePath || null),
  saveProject: (project, filePath, saveAs) => inv('project:save', { project, filePath, saveAs: !!saveAs }),
  autosaveWrite: data => inv('autosave:write', data),
  autosaveRead: () => inv('autosave:read'),
  autosaveClear: () => inv('autosave:clear'),

  defaultsGet: () => inv('defaults:get'),
  defaultsSet: s => inv('defaults:set', s),
  defaultsReset: () => inv('defaults:reset'),
  newProject: () => inv('defaults:newProject'),
  typesetsGet: () => inv('typesets:get'),
  typesetsSet: d => inv('typesets:set', d),
  profilesGet: () => inv('profiles:get'),
  profilesSet: d => inv('profiles:set', d),

  importFile: () => inv('import:file'),
  importPath: p => inv('import:path', p),
  pickImages: opts => inv('image:pick', opts || {}),
  imagesFromPaths: paths => inv('image:fromPaths', paths),
  imagesFromFileUrls: urls => inv('image:fromFileUrls', urls),
  analyzeImage: dataUrl => inv('image:analyze', dataUrl),

  libList: () => inv('lib:list'),
  libAddDialog: kind => inv('lib:addDialog', kind),
  libAddPaths: (kind, paths) => inv('lib:addPaths', kind, paths),
  libAddDataUrl: (kind, name, dataUrl) => inv('lib:addDataUrl', kind, name, dataUrl),
  libUpdate: (key, patch) => inv('lib:update', key, patch),
  libRemove: key => inv('lib:remove', key),
  libOpenFolder: () => inv('lib:openFolder'),

  fontsSystem: force => inv('fonts:system', !!force),
  fontsLibrary: () => inv('fonts:library'),
  fontsAddDialog: () => inv('fonts:addDialog'),
  fontsAddPaths: paths => inv('fonts:addPaths', paths),
  fontsAddFromSystem: fam => inv('fonts:addFromSystem', fam),
  fontsRemove: fam => inv('fonts:remove', fam),
  fontsCss: fams => inv('fonts:css', fams),

  buildBook: project => inv('book:build', project),
  layoutPrepare: project => inv('layout:prepare', project),
  layoutSegment: (buildId, key, options, priority) => inv('layout:segment', buildId, key, options, priority),
  layoutCancel: keys => inv('layout:cancel', keys),
  layoutWorkers: () => inv('layout:workers'),
  assetsPut: list => inv('assets:put', list),
  inspect: (project, opts) => inv('export:inspect', project, opts || {}),
  exportRun: req => inv('export:run', req),
  coverAnalyze: s => inv('cover:analyze', s),
  coverBookPages: project => inv('cover:bookPages', project),
  coverProof: (cover, assets, dpi) => inv('cover:proof', cover, assets, dpi),
  savePng: (name, dataUrl) => inv('dialog:savePng', name, dataUrl),
  catalogFixedGet: () => inv('catalog:fixedGet'),
  catalogFixedSet: d => inv('catalog:fixedSet', d),
  catalogTemplatesGet: () => inv('catalog:templatesGet'),
  catalogTemplatesSet: d => inv('catalog:templatesSet', d),
  publishersGet: () => inv('publishers:get'),
  publishersSet: d => inv('publishers:set', d),

  showItem: p => inv('shell:showItem', p),
  openPath: p => inv('shell:openPath', p),
  askUnsaved: () => inv('dialog:unsaved'),
  confirm: (message, detail, buttons) => inv('dialog:confirm', { message, detail, buttons }),
  saveText: (name, text) => inv('dialog:saveText', { name, text }),
  barcodeSave: (isbn, opts, format) => inv('barcode:save', { isbn, opts, format }),
  coverPickIcc: () => inv('cover:pickIcc'),
  coverFindSwop: () => inv('cover:findSwop'),
  sheetImport: () => inv('sheet:import'),
  qrDataUrl: text => inv('qr:dataUrl', text),
  creditsNext: () => inv('credits:next'),
  updateCheck: () => inv('update:check'),
  updateInstall: () => inv('update:install'),
  onUpdateProgress: cb => { const f = (e, p) => cb(p); ipcRenderer.on('update:progress', f); return () => ipcRenderer.removeListener('update:progress', f); },
  sealLogo: id => inv('seal:logo', id),
  creditsNow: () => inv('credits:now'),
  formatsGet: () => inv('formats:get'),
  formatsSet: data => inv('formats:set', data),
  systemCustomizations: () => inv('system:customizations'),
  systemReset: keys => inv('system:reset', keys),
  pendingOpen: () => inv('app:pendingOpen'),
  appInfo: () => inv('app:info'),
  closeConfirmed: () => ipcRenderer.send('app:closeConfirmed'),
  setTitle: title => ipcRenderer.send('app:setTitle', title),
  onMenu: cb => ipcRenderer.on('menu', (e, cmd) => cb(cmd)),
  enhPick: kind => inv('enh:pick', kind),
  enhRead: p => inv('enh:read', p),
  enhOcr: (p, pages) => inv('enh:ocr', p, pages),
  onEnhOcrProgress: cb => { const h = (e, d) => cb(d); ipcRenderer.on('enh:ocrProgress', h); return () => ipcRenderer.removeListener('enh:ocrProgress', h); },
  enhTarget: (base, ext, nextTo) => inv('enh:target', base, ext, nextTo),
  enhReplace: (src, docx) => inv('enh:replace', src, docx),
  enhDownloads: () => inv('enh:downloads'),
  onProgress: cb => ipcRenderer.on('progress', (e, msg) => cb(msg)),
  trPick: () => inv('tr:pick'),
  trConfig: () => inv('tr:config'),
  trSetConfig: p => inv('tr:setConfig', p),
  trTest: () => inv('tr:test'),
  trChunk: req => inv('tr:chunk', req),
  trReport: req => inv('tr:report', req),
  trSavePdf: (html, name, target) => inv('tr:savePdf', html, name, target),
  onTrProgress: cb => ipcRenderer.on('tr:progress', (e, m) => cb(m)),
  toolsPick: kind => inv('tools:pick', kind),
  toolsPickDir: () => inv('tools:pickDir'),
  toolsRead: f => inv('tools:read', f),
  toolsDecode: f => inv('tools:decode', f),
  toolsPsd: img => inv('tools:psd', img),
  toolsTarget: o => inv('tools:target', o),
  toolsWrite: (f, data) => inv('tools:write', f, data),
  toolsPdfPages: (f, dpi, max) => inv('tools:pdfPages', f, dpi, max),
  toolsPdfFromImages: (items, dpi) => inv('tools:pdfFromImages', items, dpi),
  toolsBgStatus: () => inv('tools:bgStatus'),
  toolsBgInstall: () => inv('tools:bgInstall'),
  toolsBgModel: (custom, dtype) => inv('tools:bgModel', custom, dtype),
  toolsBgMask: (bytes, mime) => inv('tools:bgMask', bytes, mime),
  onToolsBgProgress: cb => { const f = (e, m) => cb(m); ipcRenderer.on('tools:bgProgress', f); return () => ipcRenderer.removeListener('tools:bgProgress', f); },
  mtStatus: () => inv('mt:status'),
  mtInstall: key => inv('mt:install', key),
  mtRemove: key => inv('mt:remove', key),
  mtSelect: key => inv('mt:select', key),
  onMtProgress: cb => { const f = (e, m) => cb(m); ipcRenderer.on('mt:progress', f); return () => ipcRenderer.removeListener('mt:progress', f); },
  tmList: () => inv('tm:list'),
  tmAdd: req => inv('tm:add', req),
  tmRemove: id => inv('tm:remove', id),
  tmOptions: patch => inv('tm:options', patch),
  onRequestClose: cb => ipcRenderer.on('request-close', () => cb()),
  pathForFile: file => { try { return webUtils.getPathForFile(file); } catch (e) { return ''; } }
});
